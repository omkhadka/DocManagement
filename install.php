<?php
/**
 * TGISL Knowledge Hub — one-time installer.
 * Creates app/config.php, the database tables, storage folders and the first administrator.
 * After a successful install this file refuses to run again (delete app/config.php to reinstall).
 */
declare(strict_types=1);
require __DIR__ . '/app/bootstrap.php';

$done = is_file(KM_APP . '/config.php');
$errors = [];
$checks = [
    'PHP 7.4 or newer' => version_compare(PHP_VERSION, '7.4.0', '>='),
    'PDO MySQL extension' => extension_loaded('pdo_mysql'),
    'mbstring extension' => extension_loaded('mbstring'),
    'ZipArchive (Office text search, ZIP downloads)' => class_exists('ZipArchive'),
    'fileinfo extension' => extension_loaded('fileinfo'),
    'app/ folder writable' => is_writable(KM_APP),
];

if (!$done && $_SERVER['REQUEST_METHOD'] === 'POST') {
    $f = fn($k, $d = '') => trim((string)($_POST[$k] ?? $d));
    $cfg = [
        'db_host' => $f('db_host', 'localhost'), 'db_port' => (int)$f('db_port', '3306'), 'db_name' => $f('db_name'),
        'db_user' => $f('db_user'), 'db_pass' => (string)($_POST['db_pass'] ?? ''),
        'storage_path' => $f('storage_path') ?: KM_ROOT . '/storage', 'timezone' => $f('timezone', 'Africa/Nairobi'),
        'app_key' => bin2hex(random_bytes(16)),
    ];
    $adminName = $f('admin_name'); $adminEmail = strtolower($f('admin_email')); $adminPass = (string)($_POST['admin_pass'] ?? '');
    if (!$cfg['db_name'] || !$cfg['db_user']) $errors[] = 'Enter the database name and user from cPanel → MySQL Databases.';
    if (!$adminName || !filter_var($adminEmail, FILTER_VALIDATE_EMAIL)) $errors[] = 'Enter the administrator name and a valid email.';
    if (strlen($adminPass) < 10) $errors[] = 'The administrator password needs at least 10 characters.';
    if (!in_array($cfg['timezone'], timezone_identifiers_list(), true)) $cfg['timezone'] = 'Africa/Nairobi';

    if (!$errors) {
        $GLOBALS['KM_CONFIG'] = $cfg;
        try {
            $pdo = db();
            $sql = file_get_contents(KM_APP . '/schema.sql');
            $sql = preg_replace('/^--.*$/m', '', $sql);
            foreach (explode(';', $sql) as $stmt) {
                if (trim($stmt) !== '') $pdo->exec($stmt);
            }
            if ((int)val('SELECT COUNT(*) FROM users') > 0) throw new RuntimeException('This database already has users. Use an empty database, or restore app/config.php.');

            foreach (['', '/files', '/sessions', '/tmp'] as $sub) {
                $p = $cfg['storage_path'] . $sub;
                if (!is_dir($p) && !@mkdir($p, 0750, true)) throw new RuntimeException("Could not create $p. Create it in File Manager and make it writable.");
            }
            file_put_contents($cfg['storage_path'] . '/.htaccess', "<IfModule mod_authz_core.c>\n  Require all denied\n</IfModule>\n<IfModule !mod_authz_core.c>\n  Deny from all\n</IfModule>\n");
            file_put_contents($cfg['storage_path'] . '/index.html', '');

            require_once KM_APP . '/lib.php';
            require_once KM_APP . '/seed.php';
            $adminId = insert('users', ['name' => $adminName, 'email' => $adminEmail, 'password_hash' => password_hash($adminPass, PASSWORD_DEFAULT),
                'role' => 'admin', 'job_title' => $f('admin_title', 'Administrator')]);
            seed_defaults($adminId);
            if (!empty($_POST['site_name'])) set_setting('site_name', $f('site_name'));
            $scheme = (!empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off') ? 'https' : 'http';
            set_setting('base_url', $scheme . '://' . ($_SERVER['HTTP_HOST'] ?? 'localhost') . rtrim(dirname($_SERVER['SCRIPT_NAME'] ?? '/'), '/') . '/');
            if (!empty($_POST['demo'])) seed_demo($adminId, $f('demo_pass') ?: 'Welcome@2026');
            insert('audit_log', ['user_id' => $adminId, 'action' => 'install', 'object_type' => 'system', 'details' => 'Platform installed v' . KM_VERSION]);

            $php = "<?php\n// Generated by install.php on " . date('Y-m-d H:i') . ". Keep this file private.\nreturn " . var_export($cfg, true) . ";\n";
            if (file_put_contents(KM_APP . '/config.php', $php) === false) throw new RuntimeException('Could not write app/config.php. Make the app folder writable.');
            @chmod(KM_APP . '/config.php', 0640);
            $done = true;
            $justInstalled = true;
        } catch (Throwable $e) {
            $errors[] = $e->getMessage();
        }
    }
}
